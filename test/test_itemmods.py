# ---- tokens against advanced item text ------------------------------------------------------


def adv(template, nums=None):
    """Advanced text lines of a template: each # -> 'v(lo-hi)'."""
    out, k = [], 0
    for line in template.split(" / "):
        s = ""
        for ch in line:
            if ch == "#":
                v = nums[k] if nums else 12
                s += "%s(%s-%s)" % (v, v, v + 3)
                k += 1
            else:
                s += ch
        out.append(s)
    return out


def hits(rx, lines):
    r = re.compile(rx, re.I)
    return [ln for ln in lines if r.search(ln)]


