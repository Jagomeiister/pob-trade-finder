# ---- value search as the app builds it --------------------------------------------------------


def at_least(n):
    """Regex for an integer >= n (as js/app/31-regex.js does it: no left bound needed)."""
    s = str(n)
    alts = [r"[1-9]\d{%d,}" % len(s)]
    for k in range(len(s)):
        d = int(s[k])
        if k == len(s) - 1:
            alts.append(s[:k] + "[%d-9]" % d)
        elif d < 9:
            alts.append(s[:k] + "[%d-9]" % (d + 1) + r"\d" * (len(s) - k - 1))
    return "(" + "|".join(alts) + ")"


def value_term(e, n):
    num = at_least(n) + (r"(\.\d+)?" if e.get("d") else "") + r"\("
    if e.get("q"):
        return e["q"].replace("#", num)
    return e["r"] + ".*" + num if e.get("o") else num + ".*" + e["r"]


def key_line(e):
    """Index of the key number (first number on the line the token hits), its line, and its
    position among all numbers."""
    lines = e["t"].split(" / ")
    sample = adv(e["t"])
    first = 0
    for li, ln in enumerate(lines):
        if re.search(e["r"], sample[li], re.I) and "#" in ln:
            return li, first
        first += ln.count("#")
    return None, None


