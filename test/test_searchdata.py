"""Regex builder search data — run: python test/test_searchdata.py

data/searchdata.js (tools/make_searchdata.py) gives each scarab, tattoo, runegraft, gem, heist
job / target and Gwennen base a token for the game's search box (a case-insensitive regex).
Every token must find its own entry and NO other entry of its pool, nor the text every item in
that stash shows. Pools are re-derived from the cached RePoE files when they are there;
otherwise the tokens are checked against the names / descriptions in searchdata.js itself."""
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tools"))

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
failures = 0
FLAGS = re.I | re.M


def check(name, cond, detail=""):
    global failures
    failures += not cond
    print(("PASS " if cond else "FAIL ") + name + (" — " + str(detail) if detail else ""))


with open(os.path.join(ROOT, "data", "searchdata.js"), encoding="utf-8") as f:
    src = f.read()
check("searchdata.js starts with the generated-by line", src.startswith("// generated by tools/make_searchdata.py"))
m = re.search(r"window\.POE_SEARCH_DATA\s*=\s*(\{.*\});\s*$", src, re.S)
check("searchdata.js holds window.POE_SEARCH_DATA = {...};", bool(m))
D = json.loads(m.group(1)) if m else {}
LISTS = {
    "scarabs": D.get("scarabs") or [],
    "tattoos": D.get("tattoos") or [],
    "runegrafts": D.get("runegrafts") or [],
    "gems": D.get("gems") or [],
    "heist.jobs": (D.get("heist") or {}).get("jobs") or [],
    "heist.targets": (D.get("heist") or {}).get("targets") or [],
    "gwennen": D.get("gwennen") or [],
}
check("version string present", isinstance(D.get("v"), str), D.get("v"))

# ---- shape -------------------------------------------------------------------------------------
for key, rows in LISTS.items():
    check("%s is non-empty" % key, len(rows) > 0, len(rows))
    check("%s: every row has a name and a token" % key,
          all(isinstance(r.get("n"), str) and r["n"] and isinstance(r.get("t"), str) and r["t"] for r in rows))
    names = [r["n"].lower() for r in rows]
    check("%s: names are unique" % key, len(names) == len(set(names)))
    long_ = [r["t"] for r in rows if len(r["t"]) > 40]
    check("%s: no token over 40 chars" % key, not long_, long_[:3])
    plain = [r["t"] for r in rows if not r["t"].startswith("^")]
    bad = [t for t in plain if re.search(r"\d", t) or t != t.strip() or t != t.lower()]
    check("%s: plain tokens are lower-case, digit-free, no edge spaces" % key, not bad, bad[:3])
    for r in rows:
        try:
            re.compile(r["t"])
        except re.error as ex:
            check("%s: token %r compiles" % (key, r["t"]), False, ex)
check("expected list sizes", len(LISTS["scarabs"]) >= 80 and len(LISTS["gems"]) >= 500
      and len(LISTS["heist.jobs"]) == 9 and len(LISTS["gwennen"]) >= 500,
      {k: len(v) for k, v in LISTS.items()})
check("scarabs carry a family group", all(r.get("g") for r in LISTS["scarabs"]))
check("gems carry a colour r/g/b/w", all(r.get("c") in ("r", "g", "b", "w") for r in LISTS["gems"]))
check("gem flags are 1 when present", all(r.get(k, 1) == 1 for r in LISTS["gems"] for k in "sax"))
check("some supports, awakened and transfigured gems are flagged",
      all(sum(1 for r in LISTS["gems"] if r.get(k)) > 20 for k in "sax"))
check("gwennen bases carry an item class", all(r.get("c") for r in LISTS["gwennen"]))
check("tattoo stat text found for most tattoos", sum(1 for r in LISTS["tattoos"] if r.get("d")) > 80)

# ---- fallbacks match their own name line exactly ----------------------------------------------
for key, rows in LISTS.items():
    fb = [r for r in rows if r["t"].startswith("^")]
    bad = [r["t"] for r in fb if not (r["t"].endswith("$") and re.fullmatch(r["t"][1:-1], r["n"], re.I))]
    check("%s: %d ^name$ fallbacks match their own name line exactly" % (key, len(fb)), not bad, bad[:3])

# ---- uniqueness within each pool ---------------------------------------------------------------
pools = None
try:
    import make_searchdata as msd
    pools = msd.build_pools(allow_fetch=False)
    print("pools re-derived from the cached RePoE files")
except Exception as ex:  # no caches: check against what searchdata.js itself holds
    print("RePoE caches missing (%s): checking against searchdata.js names / descriptions" % ex)

for key, rows in LISTS.items():
    if pools:
        entries, extra, common = pools[key]
        text_of = {e["n"].lower(): e["_text"] for e in entries}
        check("%s: searchdata.js matches the RePoE pool (regenerate if not)" % key,
              set(text_of) == {r["n"].lower() for r in rows},
              "%d vs %d" % (len(text_of), len(rows)))
    else:
        text_of, extra, common = {}, [], ""
    texts = [text_of.get(r["n"].lower()) or "\n".join([r["n"]] + ([r["d"]] if r.get("d") else [])) for r in rows]
    if key == "tattoos" or key == "runegrafts":  # one stash section
        other = LISTS["runegrafts" if key == "tattoos" else "tattoos"]
        extra = list(extra) if pools else ["\n".join([r["n"]] + ([r["d"]] if r.get("d") else [])) for r in other]
    own_miss, clashes, common_hits = [], [], []
    for i, r in enumerate(rows):
        rx = re.compile(r["t"], FLAGS)
        if not rx.search(r["n"]) or not rx.search(texts[i]):
            own_miss.append(r["n"])
        hit = next((rows[j]["n"] for j, t in enumerate(texts) if j != i and rx.search(t)), None)
        if hit is None:
            hit = next(("(pool text) " + x.split("\n")[0] for x in extra if rx.search(x)), None)
        if hit is not None:
            clashes.append("%s: %r also finds %s" % (r["n"], r["t"], hit))
        if common and rx.search(common):
            common_hits.append(r["t"])
    check("%s: every token finds its own entry" % key, not own_miss, own_miss[:3])
    check("%s: no token finds another entry of its pool" % key, not clashes, clashes[:3])
    if pools:
        check("%s: no token finds the text every item shows" % key, not common_hits, common_hits[:3])

print("\nALL TESTS PASSED" if not failures else "\n%d FAILED" % failures)
sys.exit(1 if failures else 0)
