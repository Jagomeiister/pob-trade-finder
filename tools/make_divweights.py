"""Generate data/divweights.js: divination card drop weights, for the div cards view's value
per area.

Source: deathbeam/maps-of-exile (MIT, (c) 2023 Tomas Slusny), site/src/data/cards.json and
globals.json, pinned to COMMIT below. That project builds the weights from the Prohibited
Library's stacked deck spreadsheets (nerdyjoe's card + weight sheet, with a 3.21 sheet as the
fallback), so they're community estimates from opening stacked decks, not GGG numbers.

Per area the app works out a card's share of item drops as
  weight / (drop pool weight + weights of the cards that can drop there)
(the same model maps-of-exile uses), and from that the card value per 1,000 item drops.

Produces data/divweights.js:
  window.POE_DIV_WEIGHTS = { source, commit, league, pool, cards: { name: [weight, min area level] } }

Run: python tools/make_divweights.py   (bump COMMIT for a newer league; check the diff)
"""
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = "deathbeam/maps-of-exile"
COMMIT = "75c8bb50491c59d268c1348cf6638461d51c763b"  # 2026-11-01, league Allflame
UA = "PoBTradeFinder data build (contact: https://github.com/Jagomeiister/pob-trade-finder/issues)"


def raw(path):
    url = "https://raw.githubusercontent.com/%s/%s/%s" % (REPO, COMMIT, path)
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60) as r:
        return json.loads(r.read().decode("utf-8"))


def main():
    cards, glob = raw("site/src/data/cards.json"), raw("site/src/data/globals.json")
    pool = glob.get("droppool_weight")
    out = {}
    for c in cards:
        w = c.get("weight")
        if c.get("name") and w:
            out[c["name"]] = [round(float(w), 1), int((c.get("drop") or {}).get("min_level") or 0)]
    if not pool or len(out) < 250:
        sys.exit("weight data looks incomplete (pool %r, %d cards with a weight); not writing" % (pool, len(out)))
    data = {"source": "%s (MIT): Prohibited Library stacked deck data" % REPO, "commit": COMMIT[:12],
            "league": glob.get("league"), "pool": pool, "cards": out}
    with open(os.path.join(ROOT, "data", "divweights.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/make_divweights.py from %s @ %s (MIT, (c) 2023 Tomas Slusny)\n" % (REPO, COMMIT[:12]))
        f.write("window.POE_DIV_WEIGHTS = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("Wrote data/divweights.js: %d cards with a weight, pool %s, league %s" % (len(out), pool, glob.get("league")))


if __name__ == "__main__":
    main()
