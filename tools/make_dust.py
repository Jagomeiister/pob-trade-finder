"""Generate data/dust.js: each unique's Thaumaturgic Dust value (Kingsmarch disenchanting).

Source: deronek/poe-disenchant-tool (MIT, (c) 2025 Mateusz Dionizy), data/dust/poe-dust.js,
pinned to COMMIT below. That dataset credits a community list by alserom and PoEDB. Values
are for item level 84 at quality 0; the app scales them with the game's rules (PoE Wiki,
Kingsmarch → Disenchanting, and the formula Scalpel documents):
  dust = base × (ilvl − 64) / 20                  (item level clamped to 65–84)
              × (1 + 0.02 × quality + 0.5 × n)    (n = influence types + corruption implicits)
The dataset's ilvl-84 value already counts influences a unique always has (Starforge: Shaper,
Astrolabe: all six): its q20 column is then less than ×1.4 of q0. That count is worked out
from the two columns, (1.4 − r) / (r − 1) / 0.5 for r = q20 / q0, and stored per item.

Produces data/dust.js:
  window.POE_DUST = { source, commit, items: [[name, baseType, dust84, goldFee, slots, inf], ...] }
  (dust84 at quality 0 including the built-in influences; inf = how many it has)

Run: python tools/make_dust.py   (bump COMMIT to take a newer dataset; check the diff)
"""
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = "deronek/poe-disenchant-tool"
COMMIT = "75eb61132f2d6c94952b260f67dbb65d170332a3"  # 2026-09-24
URL = "https://raw.githubusercontent.com/%s/%s/data/dust/poe-dust.js" % (REPO, COMMIT)
UA = "PoBTradeFinder data build (contact: https://github.com/Jagomeiister/pob-trade-finder/issues)"
FIELD = re.compile(r'(name|baseType|dustValIlvl84|dustValIlvl84Q20|goldCost|slots):\s*("(?:[^"\\]|\\.)*"|\d+)')


def main():
    req = urllib.request.Request(URL, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        src = r.read().decode("utf-8")
    items, bad, influenced = [], 0, 0
    for block in re.findall(r"\{([^{}]*)\}", src):
        f = {k: json.loads(v) for k, v in FIELD.findall(block)}
        if not {"name", "baseType", "dustValIlvl84", "dustValIlvl84Q20", "goldCost", "slots"} <= set(f):
            continue
        # q20 / q0 = (1.4 + 0.5 n) / (1 + 0.5 n): n built-in influences, a whole number 0..6
        r = f["dustValIlvl84Q20"] / f["dustValIlvl84"]
        n = round((1.4 - r) / (r - 1) / 0.5) if r > 1 else -1
        if not 0 <= n <= 6 or abs((1.4 + 0.5 * n) / (1 + 0.5 * n) - r) > 0.002:
            bad += 1
            continue
        influenced += n > 0
        items.append([f["name"], f["baseType"], f["dustValIlvl84"], f["goldCost"], f["slots"], n])
    if len(items) < 800 or bad > 5:
        sys.exit("dust data looks wrong (%d items, %d that fit no influence count); not writing" % (len(items), bad))
    items.sort(key=lambda x: (-x[2], x[0]))
    data = {"source": "%s (MIT) — community list by alserom + PoEDB" % REPO, "commit": COMMIT[:12], "items": items}
    with open(os.path.join(ROOT, "data", "dust.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/make_dust.py from %s @ %s (MIT, (c) 2025 Mateusz Dionizy)\n" % (REPO, COMMIT[:12]))
        f.write("window.POE_DUST = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("Wrote data/dust.js: %d uniques, %d with built-in influences, %d skipped" % (len(items), influenced, bad))


if __name__ == "__main__":
    main()
