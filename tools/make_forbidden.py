"""Generate data/forbidden.js: the ascendancy notables Forbidden Flame / Forbidden Flesh can
allocate, with their trade stat ids (one id per node since GGG's July 2026 trade change:
explicit.stat_2460506030|<node> for Flame, explicit.stat_1190333629|<node> for Flesh), the
node's ascendancy and stats, plus Thread of Hope's ring sizes. Run after a data refresh:
  python tools/make_forbidden.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FLAME, FLESH, THREAD = "explicit.stat_2460506030", "explicit.stat_1190333629", "explicit.stat_3642528642"


def main():
    stats = json.load(open(os.path.join(ROOT, "data", "stats.json"), encoding="utf-8"))
    tree = json.load(open(os.path.join(ROOT, "data", "tree.min.json"), encoding="utf-8"))
    nodes = tree["nodes"]
    flame, flesh, rings = set(), set(), {}
    for g in stats["result"]:
        for e in g["entries"]:
            base, _, opt = e["id"].partition("|")
            if base == FLAME:
                flame.add(opt)
            elif base == FLESH:
                flesh.add(opt)
            elif base == THREAD:
                m = re.search(r"in (.+) Ring", e["text"])
                rings[int(opt)] = m.group(1) if m else e["text"]
    out, skipped = [], 0
    for nid in sorted(flame & flesh, key=int):
        n = nodes.get(nid)
        if not n or not n.get("ascendancyName"):
            skipped += 1
            continue
        out.append({"node": int(nid), "name": n.get("name", ""), "asc": n["ascendancyName"],
                    "stats": [s.replace("\n", " ") for s in n.get("stats", [])]})
    out.sort(key=lambda x: (x["asc"], x["name"]))
    data = {"flame": FLAME, "flesh": FLESH, "thread": THREAD, "notables": out,
            "rings": [[k, rings[k]] for k in sorted(rings)]}
    with open(os.path.join(ROOT, "data", "forbidden.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/make_forbidden.py from the trade stats + passive tree\n")
        f.write("window.POE_FORBIDDEN = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("Wrote data/forbidden.js: %d notables over %d ascendancies, %d Thread of Hope rings (%d ids skipped)"
          % (len(out), len({x["asc"] for x in out}), len(rings), skipped))
    return 0 if out and rings else 1


if __name__ == "__main__":
    sys.exit(main())
