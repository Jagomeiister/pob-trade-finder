"""Bundle each skill / support gem's colour (RePoE gems.json) for the socket colour helper.

Since 3.29 any gem fits any socket, but a gem in a socket of its own colour gets +10% quality,
so the gem compare says which gems sit in a matching socket.

Produces data/gemcolours.js:
  window.POE_GEM_COLOURS = { "r": "Added Fire Damage Support|Cleave|...", "g": "...", "b": "...", "w": "..." }
(names joined by "|", one string per colour: a quarter of the size of a name → colour map).

Run: python tools/make_gemcolours.py [--fetch]   (cached in data/gems.min.json, shared with make_jeweldata.py)
"""
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
UA = "PoBTradeFinder data build (contact: https://github.com/Jagomeiister/pob-trade-finder/issues)"
SRC = "https://repoe-fork.github.io/gems.min.json"


def main():
    path = os.path.join(DATA, "gems.min.json")
    if "--fetch" in sys.argv or not os.path.exists(path):
        req = urllib.request.Request(SRC, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=180) as r:
            open(path, "wb").write(r.read())
    with open(path, encoding="utf-8") as f:
        gems = json.load(f)
    by = {"r": set(), "g": set(), "b": set(), "w": set()}
    for g in gems.values():
        name, colour = (g.get("display_name") or "").strip(), g.get("color")
        if name and colour in by:
            by[colour].add(name)
    clash = set.intersection(*[by[c] for c in "rg"]) | set.intersection(*[by[c] for c in "gb"]) | \
        set.intersection(*[by[c] for c in "rb"])
    for c in by:  # a name listed under two colours (shouldn't happen): leave it out
        by[c] -= clash
    if sum(len(v) for v in by.values()) < 500:
        sys.exit("gem data looks incomplete (%d names); not writing" % sum(len(v) for v in by.values()))
    out = {c: "|".join(sorted(v)) for c, v in by.items()}
    dest = os.path.join(DATA, "gemcolours.js")
    with open(dest, "w", encoding="utf-8") as f:
        f.write("// generated by tools/make_gemcolours.py from RePoE gems.json\n")
        f.write("window.POE_GEM_COLOURS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("wrote", dest, {c: len(v) for c, v in by.items()}, "clashes dropped:", len(clash))


if __name__ == "__main__":
    main()
