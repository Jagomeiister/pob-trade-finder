"""Generate css/navicons.css: the sidebar / overlay icons, cut from one icon sheet.

The sheet (tools/art/navicons-sheet.png) is 18 gold line icons on black in a 6 x 3 grid,
generated with Higgsfield (GPT Image 2.5) in one image so they share one style. Each icon
becomes a white-on-transparent PNG mask (brightness = opacity), embedded as a data URL, and
the page paints it with `currentColor`, so the icons follow the theme and accent colours.

    python tools/make_navicons.py [sheet.png]

Order of the icons in the sheet, row by row (must match NAV_ICON_NAMES in js/app/03-shell.js).
"""
import base64
import io
import os
import sys

from PIL import Image, ImageChops

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = ["gear", "jewels", "flasks", "gems", "pasted", "planner",
         "timeless", "finder", "uniques", "search", "divcards", "tree",
         "market", "stash", "trades", "sheets", "settings", "home"]
COLS, ROWS = 6, 3
SIZE = 64          # px per icon: crisp at 18-32 CSS px on 2x screens
LO, HI = 40, 170   # brightness → opacity ramp (black background → 0, gold line → 1)


def runs(profile, min_gap):
    """Spans of non-empty positions, merging spans closer than min_gap."""
    out, start, last = [], None, None
    for i, v in enumerate(profile):
        if v:
            if start is None:
                start = i
            elif i - last > min_gap:
                out.append((start, last + 1))
                start = i
            last = i
    if start is not None:
        out.append((start, last + 1))
    return out


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tools", "art", "navicons-sheet.png")
    img = Image.open(src).convert("RGB")
    w, h = img.size
    # brightness → alpha; the sheet's line colour is gold, so the max channel is the cleanest signal
    r, g, b = img.split()
    bright = ImageChops.lighter(ImageChops.lighter(r, g), b)
    alpha = bright.point(lambda v: 0 if v <= LO else 255 if v >= HI else int((v - LO) * 255 / (HI - LO)))
    mask = alpha.point(lambda v: 255 if v > 60 else 0)
    gap = max(8, w // 60)
    bands = runs([any(mask.getpixel((x, y)) for x in range(0, w, 2)) for y in range(h)], gap)
    if len(bands) != ROWS:
        sys.exit("expected %d rows of icons, found %d" % (ROWS, len(bands)))
    rules = []
    for r, (y0, y1) in enumerate(bands):
        cols = runs([any(mask.getpixel((x, y)) for y in range(y0, y1, 2)) for x in range(w)], gap)
        if len(cols) != COLS:
            sys.exit("row %d: expected %d icons, found %d" % (r + 1, COLS, len(cols)))
        for c, (x0, x1) in enumerate(cols):
            box = alpha.crop((x0, y0, x1, y1))
            bb = box.getbbox()
            box = box.crop(bb)
            side = int(max(box.size) * 1.06)  # a hair of margin so strokes aren't clipped
            sq = Image.new("L", (side, side), 0)
            sq.paste(box, ((side - box.size[0]) // 2, (side - box.size[1]) // 2))
            # downscaling thins the strokes: lift the partial pixels so they stay solid at 18px
            sq = sq.resize((SIZE, SIZE), Image.LANCZOS).point(lambda v: min(255, int(v * 1.4)))
            icon = Image.new("RGBA", (SIZE, SIZE), (255, 255, 255, 0))
            icon.putalpha(sq)
            buf = io.BytesIO()
            icon.save(buf, "PNG", optimize=True)
            name = NAMES[r * COLS + c]
            rules.append(".ni-%s { --ni: url(data:image/png;base64,%s); }" % (name, base64.b64encode(buf.getvalue()).decode()))
    css = ("/* generated by tools/make_navicons.py from tools/art/navicons-sheet.png (Higgsfield, GPT Image 2.5).\n"
           "   Masks: the element paints them with currentColor (css/layout.css .ni). */\n" + "\n".join(rules) + "\n")
    with open(os.path.join(ROOT, "css", "navicons.css"), "w", encoding="utf-8") as f:
        f.write(css)
    print("Wrote css/navicons.css: %d icons, %d KB" % (len(rules), len(css) // 1024))


if __name__ == "__main__":
    main()
