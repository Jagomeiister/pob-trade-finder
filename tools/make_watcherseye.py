"""Generate data/watcherseye.js: the CURRENT Watcher's Eye mod pool with trade stat ids.

Source: Path of Building Community (dev branch)
  src/Data/Uniques/Special/WatchersEye.lua  every mod, with its trade hash(es) and roll range
  src/Data/Uniques/Special/Generated.lua    watchersEyeLegacyMods: removed/changed mods
Legacy mods (any entry in that table except a pure rename) are dropped, and every stat id
is checked against the bundled trade stats (data/stats.json). Run:
  python tools/make_watcherseye.py
"""
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
POB = "https://raw.githubusercontent.com/PathOfBuildingCommunity/PathOfBuilding/dev/src/"
AURAS = ["Anger", "Clarity", "Determination", "Discipline", "Grace", "Haste", "Hatred", "Malevolence", "Precision",
         "Pride", "Purity of Elements", "Purity of Fire", "Purity of Ice", "Purity of Lightning", "Vitality", "Wrath",
         "Zealotry"]
# PoB mod ids start with the aura name without spaces
PREFIX = sorted(((a.title().replace(" ", ""), a) for a in AURAS), key=lambda x: -len(x[0]))


def fetch(path):
    req = urllib.request.Request(POB + path, headers={"User-Agent": "PoBTradeFinder data build"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def legacy_ids(generated):
    i = generated.index("local watchersEyeLegacyMods = {")
    j = generated.index("\n}\n", i)
    out = set()
    for m in re.finditer(r'\["(\w+)"\] = \{(.*?)\n\t\},|\["(\w+)"\] = \{ \},', generated[i:j], re.S):
        key = m.group(1) or m.group(3)
        body = m.group(2) or ""
        if m.group(3) or "version" in body or "legacyMod" in body or "rename" not in body:
            out.add(key)
    return out


def parse_mods(lua):
    mods = []
    for m in re.finditer(r'^\t\["(\w+)"\] = \{ affix = "", (.*?), statOrder.*?tradeHashes = \{(.*?)\}, \} \},?$',
                         lua, re.M):
        key, texts_raw, hashes_raw = m.groups()
        texts = re.findall(r'"((?:[^"\\]|\\.)*)"', texts_raw)
        hashes = [int(h) for h in re.findall(r"\[(\d+)\] = \{", hashes_raw)]
        mods.append((key, texts, hashes))
    return mods


def aura_of(key):
    for p, name in PREFIX:
        if key.startswith(p):
            return name
    return None


def main():
    lua = fetch("Data/Uniques/Special/WatchersEye.lua")
    legacy = legacy_ids(fetch("Data/Uniques/Special/Generated.lua"))
    stats = json.load(open(os.path.join(ROOT, "data", "stats.json"), encoding="utf-8"))
    explicit = {e["id"]: e["text"] for g in stats["result"] if g["id"] == "explicit" for e in g["entries"]}
    out, missing = [], []
    for key, texts, hashes in parse_mods(lua):
        aura = aura_of(key)
        if not aura:
            continue  # Sublime Vision / Arbalist mods share the file
        if not hashes:
            missing.append(key)
            continue
        text = " / ".join(texts).replace("\\n", " ")
        nums = [float(x) for x in re.findall(r"\((-?[\d.]+)-(-?[\d.]+)\)", text)[0]] if "(" in text else []
        ids = ["explicit.stat_%d" % h for h in hashes]
        unknown = [i for i in ids if i not in explicit]
        if unknown:
            missing.append("%s %s" % (key, unknown))
            continue
        mod = {"key": key, "aura": aura, "ids": ids, "text": re.sub(r"\((-?[\d.]+)-(-?[\d.]+)\)", "#", text),
               "min": nums[0] if nums else None, "max": nums[1] if nums else None}
        if key in legacy:
            mod["legacy"] = 1  # no longer rolls; old jewels with it still trade (hidden unless asked for)
        out.append(mod)
    out.sort(key=lambda m: (m["aura"], m.get("legacy", 0), m["text"]))
    if missing:
        print("skipped (no aura / not on the trade site):", *missing, sep="\n  ")
    with open(os.path.join(ROOT, "data", "watcherseye.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/make_watcherseye.py from Path of Building's data; legacy = no longer rolls\n")
        f.write("window.POE_WATCHERS_EYE = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("Wrote data/watcherseye.js: %d mods (%d of them legacy), %d auras" %
          (len(out), sum(1 for m in out if m.get("legacy")), len({m["aura"] for m in out})))
    return 0 if len(out) > 50 else 1


if __name__ == "__main__":
    sys.exit(main())
